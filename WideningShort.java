class  WideningShort
{
	public static void main(String[] args) 
	{
		
		short s=300;
		System.out.println(s); // 300
		
       int i = s;
	   System.out.println(i);//300
	   
	   long l1 =s;
	   System.out.println(l1); // 300
	   
	   float f = s;
	   System.out.println(f); // 300.0
	   
	   double d = s;
	   System.out.println(d); //300.0
	   
	}
}
