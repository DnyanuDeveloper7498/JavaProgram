class DecrementOp

{
	public static void main(String[] args) 
	{
		
			int blance=200;
		
		//pre-Decrement 
		System.out.println(--blance); //199
		
		// post- Decrement
		System.out.println(blance--); // 199
		
		System.out.println(--blance + blance--); //394
		
		System.out.println(blance--);//196
		
		System.out.println(--blance); //194
		
		
	}
}
